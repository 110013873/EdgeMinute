// icon('flag', 16) → '<svg …>…</svg>'。size 省略默认 16;stroke-width 可调（小图标用细线更精致）。
export function icon(name, size = 16, sw = 2) {
  const p = PATHS[name];
  if (!p) return '';
  return `<svg class="ic ic-${name}" viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="${sw}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${p}</svg>`;
}
